/**
 * The `next/font/local` calls a theme's font files become.
 *
 * `next/font` only accepts literal arguments at module scope, so the fonts
 * every installed theme brings are written out as a module of their own,
 * `src/core/generated/theme-fonts.ts`, and the layout puts the variables it
 * exports on `html`. Paths are relative to that module, which is how
 * `next/font/local` resolves them.
 *
 * `preload` is off because every installed theme's fonts are compiled in: a
 * site wearing one theme would otherwise preload another's on every first
 * visit. A family whose file is missing is left out with a message rather
 * than failing the build, the same as a theme whose manifest does not parse.
 */
import path from "node:path";
import type { ThemeManifest } from "../../src/core/lib/theme-manifest-schema";

const HEADER = "// Auto-generated by scripts/generate-theme-registry.ts - do not edit.";

export function emitThemeFontsTs(
    themes: Record<string, ThemeManifest>,
    fileExists: (relativeToThemes: string) => boolean,
): string {
    const calls: string[] = [];
    const names: string[] = [];
    for (const [id, theme] of Object.entries(themes)) {
        for (const [family, faces] of Object.entries(theme.fontFiles ?? {})) {
            const missing = faces.find((face) => !fileExists(path.posix.join(id, face.file)));
            if (missing) {
                console.error(`[themes] ${id}: font file ${missing.file} is missing, leaving out the ${family} family`);
                continue;
            }
            const name = `${id.replace(/-/g, "_")}_${family}`;
            const src = faces.map((face) =>
                `        { path: ${JSON.stringify(`../../themes/${id}/${face.file}`)}, weight: ${JSON.stringify(face.weight)}, style: ${JSON.stringify(face.style)} },`,
            );
            calls.push(
                `const ${name} = localFont({`,
                "    src: [",
                ...src,
                "    ],",
                `    variable: ${JSON.stringify(`--font-${id}-${family}`)},`,
                '    display: "swap",',
                "    preload: false,",
                "});",
                "",
            );
            names.push(name);
        }
    }
    if (names.length === 0) {
        return [HEADER, "", 'export const themeFontVariables: string = "";', ""].join("\n");
    }
    return [
        HEADER,
        'import localFont from "next/font/local";',
        "",
        ...calls,
        `export const themeFontVariables: string = [${names.map((n) => `${n}.variable`).join(", ")}].join(" ");`,
        "",
    ].join("\n");
}
